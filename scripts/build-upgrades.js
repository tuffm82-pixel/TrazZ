// Merge the twenty independently authored gun trees into one offline-safe catalog.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const ids = ['pulse', 'scatter', 'burst', 'ricochet', 'ember', 'frost', 'arc', 'venom', 'rail', 'gravity', 'solar', 'meteor', 'wrath', 'freezepistol', 'laze', 'triangulox', 'vstruk', 'curver', 'glockbow', 'glacierar'];
const expected = ['t1-left', 't1-middle', 't1-right', 't2-left', 't2-middle', 't2-right', 't3-lm', 't3-lr', 't3-mr'];
const effects = new Set(['damage', 'fireRate', 'projectileSpeed', 'pierce', 'bounce', 'pellets', 'freeze', 'burn', 'chain', 'crit', 'lifesteal', 'abilityCooldown', 'abilityPower', 'health', 'shield']);
const trees = {};
for (const id of ids) {
  const tree = JSON.parse(fs.readFileSync(path.join(root, 'content', 'upgrades', id + '.json'), 'utf8').replace(/^\uFEFF/, ''));
  if (tree.gunId !== id || !Array.isArray(tree.nodes) || tree.nodes.length !== 9) throw new Error(`Invalid tree: ${id}`);
  const nodeIds = tree.nodes.map(n => n.id);
  if (new Set(nodeIds).size !== 9 || expected.some(n => !nodeIds.includes(n))) throw new Error(`Invalid node IDs: ${id}`);
  for (const node of tree.nodes) {
    if (!Number.isInteger(node.cost) || node.cost <= 0 || !node.name || !node.description || !node.effect || !Object.keys(node.effect).length) throw new Error(`Incomplete upgrade: ${id}/${node.id}`);
    if (node.tier !== Number(node.id[1]) || ![0, 1, 2].includes(node.column)) throw new Error(`Invalid grid position: ${id}/${node.id}`);
    for (const [key, value] of Object.entries(node.effect)) if (!effects.has(key) || !Number.isFinite(value)) throw new Error(`Unsupported effect: ${id}/${node.id}/${key}`);
    if (node.tier === 3) {
      const pairs = { 't3-lm': ['left', 'middle'], 't3-lr': ['left', 'right'], 't3-mr': ['middle', 'right'] };
      if (JSON.stringify(node.requiresPair) !== JSON.stringify(pairs[node.id])) throw new Error(`Invalid capstone pair: ${id}/${node.id}`);
    }
  }
  trees[id] = tree;
}
const output = '// Generated by scripts/build-upgrades.js. Edit content/upgrades/*.json to change a tree.\n(function(root){ const trees = ' + JSON.stringify(trees, null, 2) + '; root.TrazZUpgradeTrees = trees; if(typeof module!=="undefined" && module.exports) module.exports=trees; })(globalThis);\n';
fs.writeFileSync(path.join(root, 'upgrade-catalog.js'), output);
console.log(`Built ${ids.length} gun upgrade trees / ${ids.length * 9} nodes.`);
